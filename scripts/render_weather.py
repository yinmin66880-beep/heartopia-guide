def describe(day, copy):
    phases = day.get('phases', []) if day else []
    if not phases:
        return copy['unknown']
    parts=[]
    for phase in phases:
        label=copy['types'].get(phase.get('t'), copy['unknown'])
        if phase.get('s') is not None and phase.get('e') is not None:
            label += f" {phase['s']:02}:00–{phase['e']:02}:00"
        parts.append(label)
    return ' / '.join(parts)

def snapshot(calendar, daily, target, lang):
    copy=COPY[lang];days=calendar.get('days', {})
    upcoming=[key for key in sorted(days) if key > target][:7]
    items=''.join(f'<li><time datetime="{key}">{key}</time>: {html.escape(describe(days[key],copy))}</li>' for key in upcoming)
    if not items: items=f'<li>{copy["none"]}</li>'
    return f'''<!-- weather-snapshot:start -->
<section class="planner-snapshot" id="weatherSnapshot" aria-label="{copy['heading']}" data-snapshot-date="{target}">
  <h2>{copy['heading']}</h2>
  <p><time datetime="{target}">{target}</time> · UTC+8 · <strong>{html.escape(describe(days.get(target),copy))}</strong></p>
  <p class="planner-note">{copy['scope']} {copy['check']}</p>
  <p class="planner-note">{copy['updated']}: {html.escape(calendar.get('updated','—'))} · {copy['daily']}: {html.escape(daily.get('generatedAt','—'))} (UTC+8)</p>
  <h3>{copy['next']}</h3><ul>{items}</ul>
  <a class="planner-action" href="fishing#now">{copy['link']} →</a>
</section>
<!-- weather-snapshot:end -->'''

def render(root=ROOT, target=None):
    calendar=json.loads((root/'data-src/weather-calendar.json').read_text(encoding='utf-8'))
    daily=json.loads((root/'data/daily.json').read_text(encoding='utf-8'))
    target=target or datetime.now(BJT).date().isoformat()
    plan={'sourceOffsetMinutes':480,'sourceScope':'TapTap community calendar; other game regions not independently verified',
          'sourceUrl':calendar.get('source',{}).get('url'), 'updated':calendar.get('updated'),
          'generatedAt':daily.get('generatedAt'),'days':calendar.get('days',{})}
    output='/* Generated by scripts/render_weather.py; no inferred dates. */\nwindow.HEARTOPIA_WEATHER_PLAN = '+json.dumps(plan,ensure_ascii=False,indent=2)+';\n'
    (root/'data/weather-plan.js').write_text(output,encoding='utf-8')
    for lang in COPY:
        path=root/(lang if lang!='zh' else '')/'weather.html'
        text=path.read_text(encoding='utf-8');block=snapshot(calendar,daily,target,lang)
        pattern=r'<!-- weather-snapshot:start -->.*?<!-- weather-snapshot:end -->'
        if re.search(pattern,text,re.S):text=re.sub(pattern,lambda _:block,text,flags=re.S)
        else:text=text.replace('<main class="wrap">','<main class="wrap">\n'+block,1)
        path.write_text(text,encoding='utf-8')
    return plan

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--date')
    args=parser.parse_args()
    if args.date: datetime.strptime(args.date,'%Y-%m-%d')
    render(target=args.date)
    print('Rendered four weather snapshots and structured planner data.')
